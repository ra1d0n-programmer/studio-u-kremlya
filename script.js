const CONFIG = {
  basePrice: 4500,
  cleaningFee: 800,
  seasons: [
    { from: "2026-06-01", to: "2026-08-31", price: 5900 },
    { from: "2026-12-25", to: "2027-01-08", price: 6500 }
  ],
  bookedRanges: [
    { in: "2026-11-10", out: "2026-11-14" },
    { in: "2026-11-20", out: "2026-11-23" }
  ]
};

const form = document.getElementById("bookingForm");
const checkIn = form.checkIn;
const checkOut = form.checkOut;
const totalEl = document.getElementById("totalPrice");
const resultEl = document.getElementById("bookingResult");

const today = new Date().toISOString().split("T")[0];
checkIn.min = today;

const priceForDate = (dateStr) => {
  const d = new Date(dateStr);
  for (const s of CONFIG.seasons) {
    if (d >= new Date(s.from) && d <= new Date(s.to)) return s.price;
  }
  return CONFIG.basePrice;
};

const nightsBetween = (a, b) => Math.round((new Date(b) - new Date(a)) / 86400000);

const isRangeBooked = (inDate, outDate) => {
  const a = new Date(inDate), b = new Date(outDate);
  return CONFIG.bookedRanges.some((r) => {
    const rIn = new Date(r.in), rOut = new Date(r.out);
    return a < rOut && b > rIn;
  });
};

function calcTotal() {
  const inVal = checkIn.value, outVal = checkOut.value;
  if (!inVal || !outVal || outVal <= inVal) {
    totalEl.textContent = "—";
    return;
  }
  const nights = nightsBetween(inVal, outVal);
  let sum = CONFIG.cleaningFee;
  for (let i = 0; i < nights; i++) {
    const d = new Date(inVal);
    d.setDate(d.getDate() + i);
    sum += priceForDate(d.toISOString().split("T")[0]);
  }
  totalEl.textContent = `${sum.toLocaleString()} ₽ / ${nights} ${t("price_nights")}`;
}

checkIn.addEventListener("change", () => {
  checkOut.min = checkIn.value;
  if (checkOut.value && checkOut.value <= checkIn.value) checkOut.value = "";
  calcTotal();
});
checkOut.addEventListener("change", calcTotal);

form.addEventListener("submit", (e) => {
  e.preventDefault();
  const inVal = checkIn.value, outVal = checkOut.value;

  if (!inVal || !outVal || outVal <= inVal) return alert(t("alert_dates"));
  if (isRangeBooked(inVal, outVal)) return alert(t("alert_booked"));
  if (!form.name.value.trim() || !form.phone.value.trim()) return alert(t("alert_fields"));

  resultEl.hidden = false;
  resultEl.innerHTML = `
    <h3>${t("result_title")}</h3>
    <p>${form.name.value}, ${t("result_thanks")}</p>
    <p>${t("result_dates")}: ${inVal} → ${outVal}</p>
    <p>${totalEl.textContent}</p>
  `;
  form.reset();
  totalEl.textContent = "—";
  resultEl.scrollIntoView({ behavior: "smooth", block: "center" });
});

